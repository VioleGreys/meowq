def main():
    m = json.load(open(os.path.join(ROOT, "data/world1936/map.json"), encoding="utf-8"))
    provs = m["provinces"]
    # добыча стран
    real = {r: {} for r in RES}
    for res, tag, lon, lat, v, name in D:
        real[res][tag] = real[res].get(tag, 0.0) + v
    units = {r: {} for r in RES}
    for r in RES:
        comp = {t: v ** EXP for t, v in real[r].items()}
        k = TOTAL[r] / sum(comp.values())
        for t, c in comp.items():
            units[r][t] = c * k
    # месторождения → провинции
    out = {}
    sites = []
    missing = []
    for res, tag, lon, lat, v, name in D:
        best, bd = -1, 1e18
        for i, p in enumerate(provs):
            if p.get("land") != 1 or p.get("owner") != tag:
                continue
            dx = (p["lon"] - lon) * math.cos(math.radians(lat))
            dy = p["lat"] - lat
            d = dx * dx + dy * dy
            if d < bd:
                bd, best = d, i
        if best < 0:
            missing.append((res, tag, name))
            continue
        u = units[res][tag] * v / real[res][tag]
        row = out.setdefault(str(best), [0.0] * len(RES))
        row[RES.index(res)] += u
        sites.append((res, tag, name, best, provs[best]["name"], round(math.sqrt(bd) * 111)))
    for k in out:
        out[k] = [round(x, 2) for x in out[k]]
    data = {"_comment": "Природные ресурсы по провинциям (игровые единицы): " + ", ".join(RES) +
            ". Строится tools/build_resources.py — не править руками.",
            "resources": RES, "names": [NAMES[r] for r in RES], "provinces": out}
    with open(os.path.join(ROOT, "data/world1936/resources.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
    if missing:
        print("НЕТ ПРОВИНЦИИ:", missing)
    far = [s for s in sites if s[5] > 300]
    if far:
        print("Далеко от точки (км):", far)
    print("провинций с ресурсами:", len(out))
    if "--table" in sys.argv:
        for r in RES:
            tot_real = sum(real[r].values())
            rows = sorted(units[r].items(), key=lambda kv: -kv[1])
            print("\n%s (мир: %.0f %s → %.0f ед.)" % (NAMES[r], tot_real, UNITS[r], TOTAL[r]))
            print("  " + " · ".join("%s %.1f (%.0f%%)" % (t, u, 100 * u / TOTAL[r]) for t, u in rows))


if __name__ == "__main__":
    main()
